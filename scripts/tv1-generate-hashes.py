"""Generate the build-time constants; never import this script in a detector."""
import csv
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APIS = ("CreateFileW", "WriteFile", "CloseHandle")
VARIANTS = {
    "P1": ("api_hashing/P1_djb2", 1, 5381, ""),
    "P2": ("api_hashing/P2_fnv1a", 2, 2166136261, ""),
    "P3": ("api_hashing/P3_crc32", 3, 0xFFFFFFFF, ""),
    "P4": ("api_hashing/P4_changed_seed", 1, 1337, ""),
    "P5": ("api_hashing/P5_changed_order", 1, 5381, "#define TV1_REVERSE_ORDER\n"),
    "E1": ("error_cases/E1_wrong_hash", 1, 5381, "#define TV1_WRONG_HASH\n"),
    "E2": ("error_cases/E2_early_exit", 1, 5381, "#define TV1_EARLY_EXIT\n"),
}

def hash_name(name, algorithm, seed):
    data = name.encode("ascii")
    if algorithm == 3:
        if seed != 0xFFFFFFFF:
            raise ValueError("This CRC32 reference uses only the standard initial value")
        return zlib.crc32(data) & 0xFFFFFFFF
    h = seed
    for b in data:
        h = ((h * 33 + b) if algorithm == 1 else ((h ^ b) * 16777619)) & 0xFFFFFFFF
    return h

def main():
    rows = []
    for sample, (folder, algorithm, seed, extra) in VARIANTS.items():
        dest = ROOT / "samples" / folder
        dest.mkdir(parents=True, exist_ok=True)
        text = "/* Generated by scripts/tv1-generate-hashes.py. */\n"
        text += "#define TV1_MODE 2\n"
        text += f"#define TV1_ALGORITHM {algorithm}\n#define TV1_SEED {seed}u\n"
        for slot, api in zip(("CREATE", "WRITE", "CLOSE"), APIS):
            value = hash_name(api, algorithm, seed)
            text += f"#define TV1_TARGET_{slot} 0x{value:08X}u\n"
            rows.append([sample, algorithm, seed, api, f"0x{value:08X}"])
        text += extra + '#include "../../common/tv1_program.h"\n'
        (dest / "main.c").write_text(text, encoding="utf-8")
    for folder, mode in (("B1_static_import", 0), ("B2_dynamic_name", 1)):
        dest = ROOT / "samples/benign" / folder
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "main.c").write_text(
            f'#define TV1_MODE {mode}\n#include "../../common/tv1_program.h"\n', encoding="utf-8")
    out = ROOT / "configs/build/tv1-hash-values.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f); w.writerow(["sample_id", "algorithm", "seed", "api", "target_hash"]); w.writerows(rows)
    print("Generated 9 sample entry points and tv1-hash-values.csv")

if __name__ == "__main__":
    main()
